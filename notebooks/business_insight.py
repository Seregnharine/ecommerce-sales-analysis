import pandas as pd

# Dosya yolu
path = "/content/drive/MyDrive/olist proje/"

# Gerekli tabloları yüklüyoruz
df_items = pd.read_csv(path + "olist_order_items_dataset.csv")
df_products = pd.read_csv(path + "olist_products_dataset.csv")
df_payments = pd.read_csv(path + "olist_order_payments_dataset.csv")
df_translation = pd.read_csv(path + "product_category_name_translation.csv")

# Tabloları birleştiriyoruz
df_merged = df_items.merge(df_products, on='product_id', how='inner')
df_merged = df_merged.merge(df_payments, on='order_id', how='inner')
df_merged = df_merged.merge(df_translation, on='product_category_name', how='left')

# Kategori adına göre toplam ciro ve sipariş adedi hesaplama
category_performance = df_merged.groupby('product_category_name_english').agg(
    total_revenue=('payment_value', 'sum'),
    total_orders=('order_id', 'nunique'),
    avg_item_price=('price', 'mean')
).reset_index()

# Cirosuna göre büyükten küçüğe sıralama
category_performance = category_performance.sort_values(by='total_revenue', ascending=False)

print("🏆 En Çok Ciro Getiren İlk 10 Kategori:")
display(category_performance.head(10))